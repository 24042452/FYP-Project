import { Document, Page, StyleSheet, Text, View, renderToBuffer } from '@react-pdf/renderer'
import { formatSGD } from '../money.js'
import { formatDayLabel } from '../dashboard/home-model.js'
import { invoiceMonthLabel, invoiceStatusView } from '../invoices/model.js'

const s = StyleSheet.create({
  page: { padding: 40, fontFamily: 'Helvetica', fontSize: 11, color: '#0F1B2D' },
  name: { fontSize: 18, fontFamily: 'Helvetica-Bold' },
  muted: { color: '#5B6778', marginTop: 2 },
  title: { fontSize: 14, fontFamily: 'Helvetica-Bold', marginTop: 24, color: '#0B4DB8' },
  row: { flexDirection: 'row', justifyContent: 'space-between', paddingVertical: 6, borderBottomWidth: 1, borderBottomColor: '#E2E7EE' },
  head: { flexDirection: 'row', justifyContent: 'space-between', paddingVertical: 6, borderBottomWidth: 1, borderBottomColor: '#0F1B2D', fontFamily: 'Helvetica-Bold', marginTop: 16 },
  desc: { flexGrow: 1, paddingRight: 12 },
  total: { flexDirection: 'row', justifyContent: 'space-between', paddingVertical: 8, fontFamily: 'Helvetica-Bold', fontSize: 13 },
  footer: { position: 'absolute', bottom: 28, left: 40, right: 40, fontSize: 9, color: '#5B6778', textAlign: 'center' },
})

/**
 * @param {{inv: NonNullable<Awaited<ReturnType<typeof import('../data/invoices.js').getInvoiceWithLines>>>}} props
 */
export function InvoicePdf({ inv }) {
  const st = invoiceStatusView(inv.status, inv.dueDate)
  return (
    <Document title={`Invoice ${invoiceMonthLabel(inv.period)}`}>
      <Page size="A4" style={s.page}>
        <Text style={s.name}>{inv.merchant.legalName}</Text>
        <Text style={s.muted}>Trading as {inv.merchant.tradingName}</Text>
        <Text style={s.muted}>UEN {inv.merchant.uen}</Text>

        <Text style={s.title}>Invoice for {invoiceMonthLabel(inv.period)}</Text>
        <Text style={s.muted}>Due {formatDayLabel(inv.dueDate)} {inv.dueDate.slice(0, 4)}</Text>
        <Text style={s.muted}>Status: {st.label}</Text>

        <View style={s.head}>
          <Text style={s.desc}>Description</Text>
          <Text>Amount</Text>
        </View>
        {inv.lines.map((l) => (
          <View key={l.id} style={s.row} wrap={false}>
            <Text style={s.desc}>{l.description}</Text>
            <Text>{formatSGD(l.amountCents)}</Text>
          </View>
        ))}
        <View style={s.total}>
          <Text>Total</Text>
          <Text>{formatSGD(inv.totalCents)}</Text>
        </View>

        <Text style={s.footer} fixed>
          Sample invoice generated by the Merchant Portal prototype — not a real NETS invoice.
        </Text>
      </Page>
    </Document>
  )
}

/**
 * @param {Parameters<typeof InvoicePdf>[0]['inv']} inv
 * @returns {Promise<Buffer>}
 */
export async function renderInvoicePdf(inv) {
  return Buffer.from(await renderToBuffer(<InvoicePdf inv={inv} />))
}
