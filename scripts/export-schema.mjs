// Builds one importable .sql file from db/migrations/*.sql for a given schema (database) name.
// Usage: node scripts/export-schema.mjs <schema-name> [--no-create]
//   --no-create  leave out CREATE DATABASE / USE (import into an already-selected schema)
// Output: db/export/<schema-name>.sql
// The file also creates and fills schema_migrations, so `npm run migrate` later applies nothing new.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = path.join(root, 'db', 'migrations')
const outDir = path.join(root, 'db', 'export')

const args = process.argv.slice(2)
const name = args.find((a) => !a.startsWith('--'))
const withCreate = !args.includes('--no-create')
if (!name || !/^[A-Za-z0-9_-]{1,64}$/.test(name)) {
  console.error('Usage: node scripts/export-schema.mjs <schema-name> [--no-create]  (letters, digits, _ and - only)')
  process.exit(1)
}

const files = fs.readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort()
const q = (id) => '`' + id + '`'

const parts = [
  `-- NETS Merchant Portal: full schema for ${q(name)}`,
  `-- Generated by scripts/export-schema.mjs from db/migrations (${files.join(', ')}).`,
  '-- Do not edit by hand: change a migration and regenerate.',
  '-- Needs MySQL 8.0 (InnoDB, utf8mb4). Contains no data and no users.',
  '',
  'SET NAMES utf8mb4;',
]
if (withCreate) {
  parts.push(
    `CREATE DATABASE IF NOT EXISTS ${q(name)} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;`,
    `USE ${q(name)};`,
  )
}
for (const f of files) {
  parts.push('', `-- ===== ${f} =====`, fs.readFileSync(path.join(migrationsDir, f), 'utf8').trim())
}
parts.push(
  '',
  '-- ===== migration bookkeeping (so `npm run migrate` skips these files) =====',
  'CREATE TABLE IF NOT EXISTS schema_migrations (',
  '  name VARCHAR(200) NOT NULL PRIMARY KEY,',
  '  applied_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)',
  ') ENGINE=InnoDB;',
  'INSERT IGNORE INTO schema_migrations (name) VALUES',
  files.map((f) => `  ('${f}')`).join(',\n') + ';',
  '',
)

fs.mkdirSync(outDir, { recursive: true })
const out = path.join(outDir, `${name}.sql`)
fs.writeFileSync(out, parts.join('\n'))
console.log(`wrote ${path.relative(root, out)} (${files.length} migrations)`)
